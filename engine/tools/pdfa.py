class FontEmbedder:
    """Builds embedded TrueType replacement fonts: the font program is shared per Liberation
    face, the font dictionary is made per encoding (WinAnsi plus optional /Differences)."""

    def __init__(self, pdf: Pdf) -> None:
        self.pdf = pdf
        self.programs: dict[str, tuple[TTFontFile, Any]] = {}
        self.cache: dict[tuple[str, tuple[tuple[int, str], ...]], Dictionary] = {}

    def _descriptor(self, stem: str) -> tuple[TTFontFile, Any] | None:
        if stem in self.programs:
            return self.programs[stem]
        path = font_dir() / f"{stem}.ttf"
        if not path.is_file():
            return None
        ttf = TTFontFile(str(path))
        flags = 32  # nonsymbolic
        if "Serif" in stem:
            flags |= 2
        if "Mono" in stem:
            flags |= 1
        if "Italic" in stem:
            flags |= 64
        data = path.read_bytes()
        program = self.pdf.make_stream(data)
        program.Length1 = len(data)
        descriptor = self.pdf.make_indirect(
            Dictionary(
                Type=Name.FontDescriptor,
                FontName=Name("/" + ttf.name.decode("latin-1").replace(" ", "")),
                Flags=flags,
                FontBBox=Array([round(v) for v in ttf.bbox]),
                ItalicAngle=float(ttf.italicAngle),
                Ascent=round(ttf.ascent),
                Descent=round(ttf.descent),
                CapHeight=round(ttf.capHeight),
                StemV=int(ttf.stemV),
                FontFile2=program,
            )
        )
        self.programs[stem] = (ttf, descriptor)
        return self.programs[stem]

    def replacement(self, stem: str, differences: dict[int, str]) -> Dictionary | None:
        key = (stem, tuple(sorted(differences.items())))
        if key in self.cache:
            return self.cache[key]
        found = self._descriptor(stem)
        if found is None:
            return None
        ttf, descriptor = found
        widths = []
        for code in range(256):
            if code in differences:
                char = glyph_char(differences[code])
            elif code >= 32:
                char = bytes([code]).decode("cp1252", errors="replace")
            else:
                char = None
            width = ttf.charWidths.get(ord(char)) if char else None
            widths.append(round(width if width is not None else ttf.defaultWidth))
        encoding: Any = Name.WinAnsiEncoding
        if differences:
            array: list[Any] = []
            previous = -2
            for code, glyph in sorted(differences.items()):
                if code != previous + 1:
                    array.append(code)
                array.append(Name("/" + glyph))
                previous = code
            encoding = Dictionary(
                Type=Name.Encoding, BaseEncoding=Name.WinAnsiEncoding, Differences=Array(array)
            )
        font = self.pdf.make_indirect(
            Dictionary(
                Type=Name.Font,
                Subtype=Name.TrueType,
                BaseFont=descriptor.FontName,
                FirstChar=0,
                LastChar=255,
                Widths=Array(widths),
                Encoding=encoding,
                FontDescriptor=descriptor,
            )
        )
        self.cache[key] = font
        return font


def glyph_char(name: str) -> str | None:
    """Adobe glyph name -> character ('bullet' -> '•', 'uni20AC' -> '€')."""
    if name in _glyphname2unicode:
        return chr(_glyphname2unicode[name])
    match = re.fullmatch(r"uni([0-9A-Fa-f]{4})", name)
    return chr(int(match.group(1), 16)) if match else None


def _differences(encoding: Any) -> dict[int, str] | None:
    """Code -> glyph name from an /Encoding dictionary; None if it cannot be honoured."""
    if not isinstance(encoding, Dictionary):
        return {}
    if encoding.get("/BaseEncoding") not in (None, Name.WinAnsiEncoding, Name.StandardEncoding):
        return None
    result: dict[int, str] = {}
    code = 0
    for item in encoding.get("/Differences") or []:
        if isinstance(item, int):
            code = int(item)
            continue
        name = str(item).lstrip("/")
        if name != ".notdef":
            if glyph_char(name) is None:
                return None  # not an Adobe glyph name: PDF/A forbids it for TrueType
            result[code] = name
        code += 1
    return result


def embed_fonts(pdf: Pdf, report: Report) -> None:
    embedder = FontEmbedder(pdf)
    for res in _iter_resources(pdf):
        fonts = res.get("/Font")
        if not isinstance(fonts, Dictionary):
            continue
        for key in list(fonts.keys()):
            font = fonts[key]
            if not isinstance(font, Dictionary) or is_embedded(font):
                continue
            base = _base_name(font)
            stem = _SUBSTITUTES.get(base)
            encoding = font.get("/Encoding")
            simple = font.get("/Subtype") in (Name.Type1, Name.TrueType, Name.MMType1)
            differences: dict[int, str] | None = None
            if encoding is None or encoding in (Name.WinAnsiEncoding, Name.StandardEncoding):
                differences = {}
            elif isinstance(encoding, Dictionary):
                differences = _differences(encoding)
            replacement = (
                embedder.replacement(stem, differences)
                if stem and simple and differences is not None
                else None
            )
            if replacement is None:
                problem = f"The font '{base}' is not embedded and cannot be replaced"
                if problem not in report.problems:
                    report.problems.append(problem)
                continue
            fonts[key] = replacement
            report.fixed("fonts_embedded")


# ── colour, actions, annotations, misc ───────────────────────────────────────────────────


_CMYK_OPS = {"k", "K"}


def uses_cmyk(pdf: Pdf) -> bool:
    for obj in pdf.objects:
        if (
            isinstance(obj, pikepdf.Stream)
            and obj.get("/Subtype") == Name.Image
            and obj.get("/ColorSpace") == Name.DeviceCMYK
        ):
            return True
    for page in pdf.pages:
        try:
            for instruction in pikepdf.parse_content_stream(page):
                op = str(instruction.operator)
                if op in _CMYK_OPS:
                    return True
                if op in ("cs", "CS") and list(instruction.operands) == [Name.DeviceCMYK]:
                    return True
        except pikepdf.PdfError:
            continue
    return False


def _strip_action(holder: Any, key: str, report: Report) -> None:
    action = holder.get(key)
    if isinstance(action, Dictionary) and action.get("/S") in {Name(a) for a in _FORBIDDEN_ACTIONS}:
        del holder[key]
        report.fixed("actions_removed")


def remove_active_content(pdf: Pdf, report: Report, level: str) -> None:
    root = pdf.Root
    names = root.get("/Names")
    if isinstance(names, Dictionary):
        if "/JavaScript" in names:
            del names["/JavaScript"]
            report.fixed("javascript_removed")
        if level == "2b" and "/EmbeddedFiles" in names:
            del names["/EmbeddedFiles"]
            report.fixed("attachments_removed")
    if level == "2b" and "/AF" in root:  # associated files exist only in PDF/A-3
        del root["/AF"]
    for key in ("/AA",):
        if key in root:
            del root[key]
            report.fixed("actions_removed")
    _strip_action(root, "/OpenAction", report)
    acroform = root.get("/AcroForm")
    if isinstance(acroform, Dictionary):
        for key in ("/XFA", "/NeedAppearances"):
            if key in acroform:
                del acroform[key]
                report.fixed("form_fixes")
    if level == "3b":
        _associate_attachments(pdf, report)
    for page in pdf.pages:
        if "/AA" in page.obj:
            del page.obj["/AA"]
            report.fixed("actions_removed")
        if level == "2b" and "/AF" in page.obj:
            del page.obj["/AF"]
        annots = page.obj.get("/Annots")
        if annots is None:
            continue
        kept = Array()
        for annot in annots:
            subtype = annot.get("/Subtype")
            if subtype == Name.FileAttachment and level == "2b":
                report.fixed("attachments_removed")
                continue
            if subtype not in (Name.Popup, Name.Link) and "/AP" not in annot:
                report.fixed("annotations_removed")
                continue
            if "/AA" in annot:
                del annot["/AA"]
                report.fixed("actions_removed")
            _strip_action(annot, "/A", report)
            if subtype != Name.Popup:
                flags = int(annot.get("/F", 0))
                fixed_flags = (flags | _ANNOT_PRINT) & ~(
                    _ANNOT_HIDDEN | _ANNOT_INVISIBLE | _ANNOT_NOVIEW | _ANNOT_TOGGLE
                )
                if fixed_flags != flags:
                    annot.F = fixed_flags
                    report.fixed("annotations_fixed")
            kept.append(annot)
        page.obj.Annots = kept


def _associate_attachments(pdf: Pdf, report: Report) -> None:
    """PDF/A-3: every embedded file must be associated with the document (/AF)."""
    names = pdf.Root.get("/Names")
    tree = names.get("/EmbeddedFiles") if isinstance(names, Dictionary) else None
    if tree is None:
        return
    specs = []
    for _name, spec in pikepdf.NameTree(tree).items():
        if "/AFRelationship" not in spec:
            spec.AFRelationship = Name.Unspecified
        specs.append(spec)
    if specs:
        pdf.Root.AF = Array(specs)
        report.fixed("attachments_associated", len(specs))


def clean_objects(pdf: Pdf, report: Report) -> None:
    for obj in pdf.objects:
        if not isinstance(obj, Dictionary | pikepdf.Stream):
            continue
        if isinstance(obj, pikepdf.Stream):
            filters = obj.get("/Filter")
            names = [filters] if isinstance(filters, Name) else list(filters or [])
            if Name.LZWDecode in names:
                obj.write(obj.read_bytes())  # stored decoded; recompressed with Flate on save
                report.fixed("lzw_streams")
            if obj.get("/Subtype") == Name.Image:
                for key in ("/Alternates", "/OPI"):
                    if key in obj:
                        del obj[key]
                        report.fixed("image_fixes")
                if bool(obj.get("/Interpolate", False)):
                    obj.Interpolate = False
                    report.fixed("image_fixes")
            if obj.get("/Subtype") == Name.PS:
                report.problems.append("The file contains PostScript fragments")
        if obj.get("/Type") == Name.ExtGState:
            for key in ("/TR", "/TR2"):
                if key in obj and obj[key] != Name.Default:
                    del obj[key]
                    report.fixed("transfer_functions")
    properties = pdf.Root.get("/OCProperties")
    if isinstance(properties, Dictionary):
        configs = [properties.get("/D"), *(properties.get("/Configs") or [])]
        for config in configs:
            if isinstance(config, Dictionary):
                if "/Name" not in config:
                    config.Name = String("Default")
                if "/AS" in config:
                    del config["/AS"]


def add_output_intent(pdf: Pdf, report: Report) -> None:
    intents = pdf.Root.get("/OutputIntents")
    if intents is not None:
        for intent in intents:
            if intent.get("/S") == Name.GTS_PDFA1 and "/DestOutputProfile" in intent:
                return
    profile = pdf.make_stream(srgb_profile())
    profile.N = 3
    intent = Dictionary(
        Type=Name.OutputIntent,
        S=Name.GTS_PDFA1,
        OutputConditionIdentifier=String("sRGB IEC61966-2.1"),
        Info=String("sRGB IEC61966-2.1"),
        DestOutputProfile=profile,
    )
    pdf.Root.OutputIntents = Array([pdf.make_indirect(intent)])
    report.fixed("output_intent")


def set_identification(pdf: Pdf, level: str) -> None:
    part, conformance = LEVELS[level]
    with pdf.open_metadata(set_pikepdf_as_editor=False) as meta, warnings.catch_warnings():
        warnings.simplefilter("ignore", UserWarning)  # /Trapped has no XMP twin: dropped
        meta.load_from_docinfo(pdf.docinfo)
        meta["pdfaid:part"] = part
        meta["pdfaid:conformance"] = conformance
        meta["xmp:CreatorTool"] = "PDFForge"


def self_check(path: Path, level: str) -> list[str]:
    """Re-run the rules this tool enforces on the saved result."""
    problems = []
    with Pdf.open(path) as pdf:
        if pdf.is_encrypted:
            problems.append("The result is encrypted")
        meta = pdf.open_metadata()
        part, conformance = LEVELS[level]
        if meta.get("pdfaid:part") != part or meta.get("pdfaid:conformance") != conformance:
            problems.append("PDF/A identification missing")
        if not pdf.Root.get("/OutputIntents"):
            problems.append("No output intent")
        for font in _fonts(pdf):
            if not is_embedded(font):
                problems.append(f"The font '{_base_name(font)}' is not embedded")
        names = pdf.Root.get("/Names")
        if isinstance(names, Dictionary) and "/JavaScript" in names:
            problems.append("JavaScript present")
    return problems


