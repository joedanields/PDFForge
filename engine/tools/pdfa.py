"""PDF → PDF/A (docs/02_FEATURES.md D5) — best effort, AGPL-free (no Ghostscript, 09 §3).

PDF/A-2b and PDF/A-3b ("basic": faithful appearance) are produced with pikepdf:
- an sRGB output intent (ICC profile generated by LittleCMS via Pillow) and the XMP
  identification (pdfaid:part / conformance), synchronised with the document information;
- fonts must be embedded: the 12 Latin standard fonts (Helvetica, Times, Courier families,
  plus Arial / Times New Roman / Courier New) are replaced by the metric-compatible Liberation
  fonts that ship with the bundled LibreOffice, so text keeps its exact layout;
- forbidden features are removed: encryption, JavaScript and launch actions, additional
  actions, XFA, transfer functions, image alternates / interpolation, LZW compression,
  embedded files (2b only), non-printing or appearance-less annotations;
- what cannot be fixed without re-rendering (other non-embedded fonts, CMYK colour without a
  CMYK output intent) is reported and the file is refused rather than mislabelled.

PDF/A-1b is not offered: it needs an ICC v2 profile and no transparency, which this approach
cannot guarantee. There is no bundled validator (veraPDF needs Java); a self-check re-runs the
same rules on the result and the UI says it was checked by PDFForge.
"""

