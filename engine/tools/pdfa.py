def _convert(
    source: Path, params: dict[str, Any], level: str, work: Path, ctx: JobContext
) -> tuple[Path, Report]:
    report = Report()
    tmp = work / "pdfa.pdf"
    with open_pdf(source, passwords_map(params)) as pdf:
        if pdf.is_encrypted:
            report.fixed("encryption_removed")
        ctx.progress(10, f"Embedding fonts of {source.name}")
        embed_fonts(pdf, report)
        if uses_cmyk(pdf):
            report.problems.append(
                "The file uses CMYK (print) colours, which need a print colour profile"
            )
        if report.problems:
            raise EngineError(
                ErrorCode.UNSUPPORTED,
                f"{source.name} cannot be converted to PDF/A without changing how it looks: "
                + "; ".join(report.problems[:3])
                + ("…" if len(report.problems) > 3 else ""),
                str(source),
            )
        ctx.check_cancelled()
        ctx.progress(40, "Removing features PDF/A does not allow")
        remove_active_content(pdf, report, level)
        clean_objects(pdf, report)
        add_output_intent(pdf, report)
        set_identification(pdf, level)
        save_pdf(
            pdf,
            tmp,
            ctx,
            start=60,
            end=90,
            fix_metadata_version=True,
            compress_streams=True,
            object_stream_mode=pikepdf.ObjectStreamMode.disable,
            force_version="1.7",
        )
    problems = self_check(tmp, level)
    if problems:
        raise EngineError(
            ErrorCode.INTERNAL, f"PDF/A self-check failed for {source.name}: " + "; ".join(problems)
        )
    return tmp, report


def pdf_to_pdfa(params: dict[str, Any], ctx: JobContext) -> ToolResult:
    inputs = [Path(p) for p in require_str_list(params, "inputs", min_len=1, max_len=PDFA_MAX)]
    for path in inputs:
        check_pdf(path)
    level = option_choice(options_dict(params), "level", tuple(LEVELS), "2b")
    outputs: list[Path] = []
    totals: dict[str, int] = {}
    protected = 0
    for n, source in enumerate(inputs):
        ctx.check_cancelled()
        work = ctx.temp_dir / f"pdfa_{n:03d}"
        work.mkdir(parents=True)
        tmp, report = _convert(source, params, level, work, ctx)
        for key, value in report.fixes.items():
            totals[key] = totals.get(key, 0) + value
        if report.fixes.get("encryption_removed"):
            protected += 1
        outputs.append(deliver_pdf(tmp, params, source, "pdfa", protected=inputs))
    ctx.progress(100, "Done")
    stats: dict[str, Any] = {
        "files": len(outputs),
        "level": level,
        "validated": "self-check",
        "fixes": totals,
    }
    if protected:
        stats["protected_inputs"] = protected
    return ToolResult(outputs, stats)
