@dataclass
class Report:
    fixes: dict[str, int] = field(default_factory=dict)
    problems: list[str] = field(default_factory=list)

    def fixed(self, what: str, n: int = 1) -> None:
        self.fixes[what] = self.fixes.get(what, 0) + n


# ── helpers ───────────────────────────────────────────────────────────────────────────────


def font_dir() -> Path:
    return vendor_root() / "libreoffice" / "share" / "fonts" / "truetype"


def srgb_profile() -> bytes:
    profile = ImageCms.ImageCmsProfile(ImageCms.createProfile("sRGB"))
    data: bytes = profile.tobytes()
    return data


def _base_name(font: Dictionary) -> str:
    return _SUBSET.sub("", str(font.get("/BaseFont", "/")).lstrip("/")).replace(" ", "")


def _descriptor(font: Dictionary) -> Any:
    if font.get("/Subtype") == Name.Type0:
        descendants = font.get("/DescendantFonts")
        if not descendants:
            return None
        return descendants[0].get("/FontDescriptor")
    return font.get("/FontDescriptor")


def is_embedded(font: Dictionary) -> bool:
    if font.get("/Subtype") == Name.Type3:
        return True
    descriptor = _descriptor(font)
    return descriptor is not None and any(k in descriptor for k in _EMBEDDED_KEYS)


def _iter_resources(pdf: Pdf) -> list[Dictionary]:
    """Every resource dictionary: pages, form XObjects, annotation appearances, patterns."""
    found: list[Dictionary] = []
    seen: set[tuple[int, int]] = set()

    def visit(res: Any) -> None:
        if not isinstance(res, Dictionary):
            return
        key = res.objgen if res.is_indirect else None
        if key and key in seen:
            return
        if key:
            seen.add(key)
        found.append(res)
        for group in ("/XObject", "/Pattern"):
            for _n, obj in (res.get(group) or Dictionary()).items():
                if isinstance(obj, pikepdf.Stream | Dictionary) and obj.is_indirect:
                    if obj.objgen in seen:
                        continue
                    seen.add(obj.objgen)
                    visit(obj.get("/Resources"))
        for _n, font in (res.get("/Font") or Dictionary()).items():
            if font.get("/Subtype") == Name.Type3:
                visit(font.get("/Resources"))

    for page in pdf.pages:
        visit(page.obj.get("/Resources"))
        for annot in page.obj.get("/Annots") or Array():
            for appearance in (annot.get("/AP") or Dictionary()).values():
                streams = (
                    appearance.values()
                    if isinstance(appearance, Dictionary)
                    and not isinstance(appearance, pikepdf.Stream)
                    else [appearance]
                )
                for stream in streams:
                    if isinstance(stream, pikepdf.Stream):
                        visit(stream.get("/Resources"))
    acroform = pdf.Root.get("/AcroForm")
    if acroform is not None:
        visit(acroform.get("/DR"))
    return found


def _fonts(pdf: Pdf) -> list[Dictionary]:
    fonts: dict[tuple[int, int] | int, Dictionary] = {}
    for res in _iter_resources(pdf):
        for _n, font in (res.get("/Font") or Dictionary()).items():
            if isinstance(font, Dictionary):
                fonts[font.objgen if font.is_indirect else id(font)] = font
    return list(fonts.values())


